#!/usr/bin/env python3
"""Enclave OS — the installer's world map (Calamares localeq page).

Writes into arch/overlay/airootfs/etc/calamares/branding/enclave/:
  worldmap-dots.png  a dot-matrix world (white dots; the page tints and
                     glows them), equirectangular, 84°N … 57.75°S, square cells
  zones.js           every tz zone with its city, country and coordinates
                     (from tzdata's zone.tab / iso3166.tab), so the page can
                     place the pin, search cities and snap clicks to a zone

  tools/make-installer-map.py LAND.geojson ZONE.tab ISO3166.tab

LAND.geojson is Natural Earth's ne_110m_land (public domain); the tz tables
are tzdata's (public domain). Run once and commit the outputs; the page's
projection (NORTH / SOUTH below) must match localeq.qml.
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

NORTH = 84.0                        # the map's top edge (zones.js tells the page)
STEP = 2.25                         # degrees between dots (big enough to stay crisp)
ROWS = 63                           # down to NORTH - ROWS*STEP = 57.75°S
SOUTH = NORTH - ROWS * STEP
CELL = 10                           # pixels per dot cell
OUT = Path(__file__).resolve().parent.parent / "arch/overlay/airootfs/etc/calamares/branding/enclave"


def main(land, zonetab, iso):
    cols = int(360 / STEP)
    rows = ROWS
    W, H = cols * CELL, rows * CELL

    # land mask at 4x the grid, then coverage per cell
    S = 4
    mw, mh = cols * S, rows * S
    mask = Image.new("L", (mw, mh), 0)
    d = ImageDraw.Draw(mask)

    def px(lon, lat):
        return ((lon + 180) / 360 * mw, (NORTH - lat) / (NORTH - SOUTH) * mh)

    for f in json.load(open(land, encoding="utf-8"))["features"]:
        g = f["geometry"]
        polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for poly in polys:
            d.polygon([px(*pt[:2]) for pt in poly[0]], fill=255)
            for hole in poly[1:]:
                d.polygon([px(*pt[:2]) for pt in hole], fill=0)

    small = mask.resize((cols, rows), Image.BOX)
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    dots = ImageDraw.Draw(img)
    r = CELL * 0.31
    n = 0
    for y in range(rows):
        for x in range(cols):
            cover = small.getpixel((x, y)) / 255
            if cover < 0.30:
                continue
            a = int(255 * (0.55 + 0.45 * min(1, cover)))
            cx, cy = x * CELL + CELL / 2, y * CELL + CELL / 2
            dots.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(255, 255, 255, a))
            n += 1
    img.save(OUT / "worldmap-dots.png", optimize=True)

    countries = {}
    for line in open(iso, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        cc, name = line.rstrip("\n").split("\t")[:2]
        countries[cc] = name

    def coord(s, deg):
        sign = -1 if s[0] == "-" else 1
        s = s[1:]
        v = int(s[:deg]) + int(s[deg:deg + 2]) / 60
        if len(s) > deg + 2:
            v += int(s[deg + 2:deg + 4]) / 3600
        return round(sign * v, 3)

    zones = []
    for line in open(zonetab, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        cc, co, tz = line.rstrip("\n").split("\t")[:3]
        if "/" not in tz:
            continue
        cut = 5 if co[5] in "+-" else 7          # ±DDMM or ±DDMMSS
        lat, lon = coord(co[:cut], 2), coord(co[cut:], 3)
        region, zone = tz.split("/", 1)
        city = zone.split("/")[-1].replace("_", " ")
        zones.append([region, zone, city, countries.get(cc, cc), lat, lon])
    zones.sort(key=lambda z: z[2])
    with open(OUT / "zones.js", "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/make-installer-map.py from tzdata (public domain).\n")
        f.write("// [region, zone, city, country, latitude, longitude]\n.pragma library\n")
        f.write("var north = %s, south = %s;\nvar list = [\n" % (NORTH, SOUTH))
        f.write(",\n".join(json.dumps(z, ensure_ascii=False) for z in zones))
        f.write("\n];\n")
    print(f"worldmap-dots.png {W}x{H}, {n} dots; zones.js {len(zones)} zones")


if __name__ == "__main__":
    main(*sys.argv[1:4])
