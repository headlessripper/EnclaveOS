def tile(kind):
    stops, (rim, top, bottom) = TILES[kind]
    defs = grad('tile', stops, 0, 8, 0, 120) + grad(
        'rim', [(0, rim, top), (1, rim, bottom)], 0, 8, 0, 120)
    shadow_colour = '#7A2E08' if kind == 'ember' else '#000000'
    body = (f'<path d="{TILE}" fill="{shadow_colour}" opacity="0.10" transform="translate(0 3)"/>'
            f'<path d="{TILE}" fill="{shadow_colour}" opacity="0.14" transform="translate(0 1.2)"/>'
            f'<path d="{TILE}" fill="url(#tile)"/>'
            f'<path d="{TILE}" fill="none" stroke="url(#rim)" stroke-width="1.2"/>')
    return defs, body


def svg(title, defs, body):
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">\n'
            f'  <!-- Enclave Icons — {title}. Generated by tools/make-icons.py; edit there. -->\n'
            f'  <defs>{defs}</defs>\n  {body}\n</svg>\n')


def app(title, kind, defs, glyph):
    tdefs, tbody = tile(kind)
    return svg(title, tdefs + defs, tbody + glyph)


def gear(cx, cy, ro, ri, teeth, top=0.30, base=0.52):
    pts = []
    pitch = 2 * math.pi / teeth
    for k in range(teeth):
        a = k * pitch - math.pi / 2
        hb, ht = pitch * base / 2, pitch * top / 2
        for ang, r in ((a - hb, ri), (a - ht, ro), (a + ht, ro), (a + hb, ri), (a + pitch / 2, ri)):
            pts.append((cx + r * math.cos(ang), cy + r * math.sin(ang)))
    return 'M' + ' L'.join(f'{x:.1f} {y:.1f}' for x, y in pts) + ' Z'


