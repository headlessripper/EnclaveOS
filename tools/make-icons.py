# ---------------------------------------------------------------- write
def write(sub, name, text, aliases=()):
    d = os.path.join(OUT, sub)
    os.makedirs(d, exist_ok=True)
    for n in (name, *aliases):
        with open(os.path.join(d, n + '.svg'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    count = 0
    for name, (_label, aliases, make) in APPS.items():
        write('apps', name, make(), aliases)
        count += 1
    for name in EMBLEMS:
        write('places', name, folder(name), PLACE_ALIASES.get(name, ()))
        count += 1
    write('places', 'user-trash', trash(False), PLACE_ALIASES['user-trash'])
    write('places', 'user-trash-full', trash(True), PLACE_ALIASES['user-trash-full'])
    count += 2
    for name, (make, aliases) in DEVICES.items():
        write('devices', name, make(), aliases)
        count += 1
    write('mimetypes', 'inode-directory', folder('folder'))
    files = sum(len(fs) for _, _, fs in os.walk(OUT))
    print(f'Enclave Icons: {count} designs, {files} files in {os.path.normpath(OUT)}')


if __name__ == '__main__':
    main()
