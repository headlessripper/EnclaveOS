# ---------------------------------------------------------------- helpers
def squircle(cx=64, cy=64, r=56, n=4.6, steps=128):
    """Superellipse |x|^n + |y|^n = r^n — Enclave's continuous-corner tile."""
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        x = cx + r * math.copysign(abs(c) ** (2 / n), c)
        y = cy + r * math.copysign(abs(s) ** (2 / n), s)
        pts.append(f'{x:.1f} {y:.1f}')
    return 'M' + ' L'.join(pts) + ' Z'


TILE = squircle()


def grad(gid, stops, x1, y1, x2, y2):
    """A user-space linear gradient (works on strokes and thin shapes too)."""
    s = ''.join(
        f'<stop offset="{o}" stop-color="{c}"' + (f' stop-opacity="{a}"' if a != 1 else '') + '/>'
        for o, c, a in ((st + (1,))[:3] for st in stops))
    return (f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" '
            f'x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">{s}</linearGradient>')


